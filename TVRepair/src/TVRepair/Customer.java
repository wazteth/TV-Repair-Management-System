    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) tblCustomer.getModel();
        int index = tblCustomer.getSelectedRow();
        String id = model.getValueAt(index, 0).toString();

        if (index >= 0) {
            String url = "jdbc:mysql://localhost:3306/RepairDB";
            String driver = "com.mysql.jdbc.Driver";
            String username = "root";
            String password = "root";
            try {
                con = DriverManager.getConnection(url, username, password);
                stmt = con.createStatement();
                String sql = "update Customer set Customer_Name='" + txtName.getText() + "',"
                        + "Customer_Add='" + txtAddress.getText() + "',Customer_Tel='" + txtTelephone.getText() + "',"
                        + "Customer_Email='" + txtEmail.getText() + "',Customer_Gender='"+txtGender.getText()+"',Customer_Age='"+txtAge.getText()+"' where Customer_ID ='" + id + "'";
                stmt.executeUpdate(sql);
                JOptionPane.showMessageDialog(this, "Updated Success!!!");
                showData();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, e.getMessage());
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a row to update!!!");
            return;
        }
        
    }//GEN-LAST:event_btnUpdateActionPerformed

