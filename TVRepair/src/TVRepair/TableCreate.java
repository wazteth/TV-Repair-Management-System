private String[] Data1() {
        String cName = txtC1.getText();
        String dType = cboType1.getSelectedItem().toString();
        String st;
        String pKey = "";
        if (chkN1.isSelected()) {
            st = "NOT NULL";
        } else {
            st = "NULL";
        }
        if (chkP1.isSelected()) {
            if (!chkN1.isSelected()) {
                JOptionPane.showMessageDialog(this, "Primary Key can't be NULL, please check NOT NULL");
                return null;
            } else {
                pKey = "Primary Key";
                st = "NOT NULL";
            }
        }
        String[] result = {cName, dType, st, pKey};
        return result;
    }

    private String[] Data2() {
        String cName = txtC2.getText();
        String dType = cboType2.getSelectedItem().toString();
        String st;
        String pKey = "";
        if (chkN2.isSelected()) {
            st = "NOT NULL";
        } else {
            st = "NULL";
        }
        if (chkP2.isSelected()) {
            if (!chkN2.isSelected()) {
                JOptionPane.showMessageDialog(this, "Primary Key can't be NULL, please check NOT NULL");
                return null;
            } else {
                pKey = "Primary Key";
                st = "NOT NULL";
            }
        }

        String[] previous = Data1();
        String[] current = {cName, dType, st, pKey};
        String[] result = new String[previous.length + current.length];
        System.arraycopy(previous, 0, result, 0, previous.length);
        System.arraycopy(current, 0, result, 4, current.length);
        return result;
    }

