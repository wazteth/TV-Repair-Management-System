    private void displayData() {
        try {
            Class.forName("com.mysql.jdbc.Driver");
            con = DriverManager.getConnection("jdbc:mysql://localhost:3306/RepairDB", "root", "root");

            String sql = "describe " + cboTable.getSelectedItem() + "";

            PreparedStatement pstmt = con.prepareStatement(sql);
            rs = pstmt.executeQuery();

//        tblUpdate.setModel(DbUtils.resultSetToTableModel(rs));
            
            ResultSetMetaData metaData = rs.getMetaData();
            int columnCount = metaData.getColumnCount();

            // Assuming tblUpdate already has a DefaultTableModel set
            DefaultTableModel model = (DefaultTableModel) tblUpdate.getModel();

            // Clear existing rows
            model.setRowCount(0);

            // Add new rows
            while (rs.next()) {
                Object[] row = new Object[columnCount];
                for (int i = 1; i <= columnCount; i++) {
                    row[i-1]=(rs.getObject(i));
                }
                model.addRow(row);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }
    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        String cName = txtCName.getText();
        String dType = cboType.getSelectedItem().toString();
        String st;
        String pKey = "";
        if (chkN1.isSelected()) {
            st = "NULL";
        } else {
            st = "NOT NULL";
        }
        if (chkP1.isSelected()) {
            if (chkN1.isSelected()) {
                JOptionPane.showMessageDialog(this, "Primary Key can't be NULL, please check NOT NULL");
                return;
            } else {
                pKey = "Primary Key";
                st = "NOT NULL";
            }
        }
        try {
            Class.forName("com.mysql.jdbc.Driver");
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/RepairDB", "root", "root");

            String query = "alter table " + cboTable.getSelectedItem() + " add " + cName + " " + dType + " " + st + " " + pKey + "";
            PreparedStatement pstmt = con.prepareStatement(query);
            pstmt.execute(); // execute for DDL
            JOptionPane.showMessageDialog(this, "New Column is added!!!");
            displayData();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int index = tblUpdate.getSelectedRow();
        String oldName = tblUpdate.getValueAt(index, 0).toString();
        String newName = txtCName.getText();
        String dType = cboType.getSelectedItem().toString();
        String st;
        if (chkN1.isSelected()) {
            st = "NULL";
        } else {
            st = "NOT NULL";
        }

        try {
            Class.forName("com.mysql.jdbc.Driver");
            con = DriverManager.getConnection("jdbc:mysql://localhost:3306/RepairDB", "root", "root");

            String sql = "alter table " + cboTable.getSelectedItem() + " change column " + oldName + " " + newName + " " + dType + " " + st + "";

            PreparedStatement pstmt = con.prepareStatement(sql);
            pstmt.execute();

            JOptionPane.showMessageDialog(this, "Column is Updated");
            displayData();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

