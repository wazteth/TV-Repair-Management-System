    private void btnDeleteTableActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteTableActionPerformed
        // TODO add your handling code here:
         int response = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to proceed?",
            "Confirmation",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.QUESTION_MESSAGE
        );
         if (response == JOptionPane.YES_OPTION){
        try {
            Class.forName("com.mysql.jdbc.Driver");
            con = DriverManager.getConnection("jdbc:mysql://localhost:3306/RepairDB", "root", "root");

            String sql = "drop table " + cboTable.getSelectedItem() + "";
            PreparedStatement pstmt = con.prepareStatement(sql);
            pstmt.execute();

            String selectedTable = (String) cboTable.getSelectedItem();
            //cboTable.getSelectedItem().toString();

            JOptionPane.showMessageDialog(this, "Table Deleted Successfully");
            cboTable.removeItem(selectedTable);

            cboTable.setSelectedIndex(1);
            displayData();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }}
    }//GEN-LAST:event_btnDeleteTableActionPerformed

